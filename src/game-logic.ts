export class TileObject {
    key: number;
    flagged: boolean;
    nCount: number;
    covered: boolean;
    bomb:boolean;

    public constructor(key: number, neighbours: number){
        this.flagged = false;
        this.covered = true;
        this.key = key;
        this.nCount = neighbours;
        this.bomb = neighbours===-1;
    }
}

export function emptyGeneration(size: number){
    const tiles: TileObject[] = new Array(size);
    for(let i = 0; i<size*size; i++){
        tiles[i] = new TileObject(i, 0);
    }
    return tiles;
}
export function generation(size: number, gen: string){
    switch(gen){
        case GenModes.Classic:
            return classicGeneration(size);
        case GenModes.Random:
            return randomGeneration(size);
    }
    return [];
}

